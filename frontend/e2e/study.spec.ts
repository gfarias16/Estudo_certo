import { test, expect } from '@playwright/test'
import path from 'node:path'

test('estudante entra, erra, revisa e acompanha o resultado persistido', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByLabel('Usuário').fill('estudante-e2e')
  await page.getByLabel('Senha', { exact: true }).fill(process.env.E2E_PASSWORD!)
  await page.getByRole('button', { name: 'Entrar no meu estudo' }).click()
  await expect(page.getByRole('heading', { name: 'Vamos avançar, Estudante.' })).toBeVisible()
  await page.screenshot({ path: path.resolve('../.local/dashboard-desktop.png'), fullPage: true })
  await page.getByRole('button', { name: 'Ativar tema claro' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.screenshot({ path: path.resolve('../.local/dashboard-desktop-light.png'), fullPage: true })
  await page.getByRole('button', { name: 'Ativar tema escuro' }).click()
  await page.getByRole('link', { name: 'Questões', exact: true }).click()
  await page.getByLabel('Tema do estatuto').selectOption('fundamentos')
  await expect(page.getByText('Qual é o objeto da Lei municipal nº 1.625/2026?')).toBeVisible()
  const questionResponse = await page.request.get('/api/v1/questions/?topic=fundamentos')
  const publicQuestion = (await questionResponse.json()).results[0]
  expect(publicQuestion).not.toHaveProperty('correct_choice')
  expect(publicQuestion.options[0]).not.toHaveProperty('explanation')
  await page.getByRole('radio', { name: /Instituir o estatuto de todas as polícias estaduais/ }).check()
  await page.getByRole('button', { name: 'Confirmar resposta' }).click()
  await expect(page.getByRole('heading', { name: 'Um ponto para revisar.' })).toBeVisible()
  await expect(page.getByText('Art. 1º', { exact: true })).toBeVisible()
  await page.screenshot({ path: path.resolve('../.local/correcao-desktop.png'), fullPage: true })
  await page.getByRole('link', { name: 'Caderno de erros', exact: true }).click()
  await expect(page.getByText('Qual é o objeto da Lei municipal nº 1.625/2026?')).toBeVisible()
  await page.getByRole('radio', { name: /Instituir o estatuto dos servidores da Guarda Municipal de São Gonçalo/ }).check()
  await page.getByRole('button', { name: 'Confirmar resposta' }).click()
  await expect(page.getByRole('heading', { name: 'Resposta correta. Continue assim.' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Nenhum erro pendente nesta seleção.' })).toBeVisible()
  await page.getByRole('link', { name: 'Desempenho', exact: true }).click()
  await expect(page.getByText('1 corretas · 1 incorretas')).toBeVisible()
  const stats = await (await page.request.get('/api/v1/overview/')).json()
  expect(stats.total_attempts).toBe(2)
  expect(stats.first_accuracy).toBe(0)
  expect(stats.accuracy).toBe(50)
  expect(stats.pending_errors).toBe(0)
  await page.getByRole('link', { name: 'Plano de estudo', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Saiba de onde vem o conteúdo' })).toBeVisible()
  await page.getByRole('link', { name: 'Minha conta' }).click()
  await page.getByLabel('Minutos por dia').fill('60')
  await page.getByRole('button', { name: 'Salvar meta' }).click()
  await expect(page.getByText('Meta de estudo atualizada.')).toBeVisible()
  await page.getByRole('link', { name: 'Meu estudo', exact: true }).click()
  await page.setViewportSize({ width: 375, height: 812 })
  await expect(page.getByRole('heading', { name: 'Vamos avançar, Estudante.' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: path.resolve('../.local/dashboard-mobile.png'), fullPage: true })
  await page.getByRole('link', { name: 'Questões', exact: true }).click()
  await page.getByLabel('Tema do estatuto').selectOption('fundamentos')
  await expect(page.getByRole('button', { name: 'Confirmar resposta' })).toBeDisabled()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: path.resolve('../.local/questao-mobile.png'), fullPage: true })
  await page.getByRole('button', { name: 'Ativar tema claro' }).click()
  await page.screenshot({ path: path.resolve('../.local/questao-mobile-light.png'), fullPage: true })
  await page.getByRole('button', { name: 'Ativar tema escuro' }).click()
  await page.getByRole('button', { name: 'Sair da conta', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Entrar no meu estudo' })).toBeVisible()
  expect(errors).toEqual([])
})

test('rejeita login inválido com mensagem visível', async ({ page }) => {
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  await page.getByLabel('Usuário').fill('nao-existe')
  await page.getByLabel('Senha', { exact: true }).fill('somente-para-teste-isolado')
  await page.getByRole('button', { name: 'Entrar no meu estudo' }).click()
  await expect(page.getByRole('alert')).toContainText('Usuário ou senha inválidos.')
})

test('tema escuro e padrao mesmo com sistema claro e escolha persiste ao recarregar', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'light' })
  await page.goto('/', { waitUntil: 'networkidle' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('button', { name: 'Ativar tema claro' }).click()
  await page.reload({ waitUntil: 'networkidle' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.getByRole('button', { name: 'Ativar tema escuro' }).click()
  await page.reload({ waitUntil: 'networkidle' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
})
